import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const cssOutFile = join(repoRoot, "web-remote", "src", "generatedDesktopUi.ts");
const backdropOutFile = join(repoRoot, "web-remote", "src", "generatedDesktopBackdrop.ts");

const files = [
  "client/src/styles/global.css",
  "client/src/styles/sidebar.css",
  "client/src/styles/thread.css",
  "client/src/styles/composer.css",
  "client/src/styles/login.css"
];

const css = files
  .map((file) => `/* ${file} */\n${readFileSync(join(repoRoot, file), "utf8")}`)
  .join("\n\n")
  .replaceAll('url("../piagent-icon.ico")', 'url("/piagent-icon.ico")')
  .replaceAll("url('../piagent-icon.ico')", 'url("/piagent-icon.ico")');

writeFileSync(
  cssOutFile,
  [
    "// This file is generated by web-remote/scripts/sync-desktop-ui.mjs.",
    "// Do not edit it directly. Edit client/src/styles/*.css instead.",
    `export const desktopUiCss = ${JSON.stringify(css)};`,
    ""
  ].join("\n")
);

const backdropSource = readFileSync(join(repoRoot, "client/src/lib/animatedBackdropCore.ts"), "utf8");
const backdropJs = ts.transpileModule(backdropSource, {
  compilerOptions: {
    module: ts.ModuleKind.ES2020,
    target: ts.ScriptTarget.ES2020,
    removeComments: true
  }
}).outputText
  .replace(/^export\s+/gm, "")
  .replace(/\nexport\s+\{[^}]+\};?\s*$/m, "");

const backdropScript = [
  "(() => {",
  backdropJs,
  "window.PiAgentAnimatedBackdrop = { startAnimatedBackdrop };",
  "})();"
].join("\n");

writeFileSync(
  backdropOutFile,
  [
    "// This file is generated by web-remote/scripts/sync-desktop-ui.mjs.",
    "// Do not edit it directly. Edit client/src/lib/animatedBackdropCore.ts instead.",
    `export const desktopBackdropScript = ${JSON.stringify(backdropScript)};`,
    ""
  ].join("\n")
);
